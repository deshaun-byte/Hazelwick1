import random
n = random.randint(1, 100)
guess = int(input("Guess a number between 1 and 100: "))
if guess == n:
    print("+10 points")
elif n - 5 < guess < n + 5:
    print("+5 points")
elif n - 10 < guess < n + 10:
    print("+2 points")
else:
    print("0 points")
